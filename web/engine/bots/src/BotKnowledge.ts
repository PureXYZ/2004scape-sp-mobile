// ─────────────────────────────────────────────────────────────────────────────
// Skill progression steps
//
// XP values are the internal engine format (×10):
//   engine stores "25.0 xp" as 250, "37.5 xp" as 375, etc.
//   Verified against:
//     Woodcutting: trees.dbrow    (productexp field)
//     Fishing:     fishing.struct (productexp field)
//     Mining:      mine.dbrow     (rock_exp field)
//     Cooking:     cooking_generic.dbrow (experience field)
//     Firemaking:  firemaking.obj (productexp field)
//     Smithing:    smelting.struct (productexp field)
//     Combat:      combat.rs2     (scale(400,100,damage*10))
//     Prayer:      bones bury = 45 (4.5xp), big bones = 150 (15xp)
//
// ACCESSIBILITY NOTES:
//   All active combat/skilling locations use gate-free spots OR are handled
//   by BotAction.walkTo() gateway routing (AlKharid, AlKharidExit, CowPen,
//   VarrockNorth, PortSarimToKaramja, KaramjaToPortSarim).
//   Karamja fishing (lobster/swordfish) is routed via the Port Sarim boat
//   gateways — bots teleport through the toll in both directions.
// ─────────────────────────────────────────────────────────────────────────────

export interface SkillStep {
    minLevel: number;
    maxLevel: number;
    action: string;
    location: [number, number, number];
    via?: [number, number, number]; // optional waypoint to route through before location
    toolItemIds: number[];
    xpPerAction: number;
    ticksPerAction: number;
    successRate: number;
    itemGained?: number;
    itemConsumed?: number;
    extra?: Record<string, unknown> & {
        itemsGained?: string[]; // item names for finding ground objects; // multiple items from a single action (e.g., chicken drops bones + feather + raw chicken)
    };
    /**
     * port (the realism work, phase 3: "2004 hotspots"): how much more often than an ordinary spot this one is
     * picked, where 2004's crowds were (Lumbridge's chickens, cows and goblins, Al Kharid's
     * warriors, the barbarians, the giants): a weight on top of "nearer spots more often" (pickNear). 1 when unset.
     */
    crowd?: number;
    /**
     * port (the same): minLevel-maxLevel is the band of levels the spot suits, as 2004's fighters used it (chickens and
     * goblins to 15, cows to 25, Al Kharid's warriors 15-45, barbarians 10-35, giants 30-65): within its band it is always
     * a suited step (suitedSteps), whatever the best step of the level is; outside it never.
     */
    levelBand?: boolean;
}

