/**
 * Woodcutting step that produces a specific log type at the given WC level.
 * Returns null if the bot's WC level is too low to cut those logs yet.
 * Used by the planner to send a bot to gather the exact logs it needs for
 * Firemaking or Fletching before it can do those skills.
 */
export function getWoodcuttingStepForLog(logId: number, wcLevel: number, from?: [number, number]): SkillStep | null {
    const steps = SkillProgression['WOODCUTTING'] ?? [];
    const matching = steps.filter(s => s.itemGained === logId && wcLevel >= s.minLevel && wcLevel <= s.maxLevel);
    if (matching.length === 0) return null;
    // (the variety work, round 1, Track D: `from`, where the bot is: the nearer grove the likelier, and a busy one less
    // (pickNear); a fletcher drew Seers', Catherby's or Port Sarim's willows alike after every load, wherever it was)
    return pickNear(matching, from);
}

/**
 * Highest-tier log the bot's Woodcutting level can actually chop, regardless
 * of what any other skill (e.g. Fletching) might otherwise be eligible for.
 * Falls back to regular Items.LOGS (always choppable from level 1) if no
 * WOODCUTTING step data is found.
 */
export function bestLogForWoodcutting(wcLevel: number): number {
    const steps = SkillProgression['WOODCUTTING'] ?? [];
    const matching = steps.filter(s => wcLevel >= s.minLevel && s.itemGained !== undefined);
    if (matching.length === 0) return Items.LOGS;
    return matching.reduce((best, s) => (s.minLevel > best.minLevel ? s : best)).itemGained!;
}

/**
 * Best fletch_ step (highest minLevel, i.e. shortbow < longbow of the same
 * log) that consumes a specific log type and is reachable at the given
 * Fletching level. Used to re-target FletchingTask onto the best log tier
 * the bot's Woodcutting can actually supply — see bestLogForWoodcutting()
 * and FletchingTask._reconcileStep().
 */
export function getBestFletchStepForLog(logId: number, fletchLevel: number): SkillStep | null {
    const steps = SkillProgression['FLETCHING'] ?? [];
    const matching = steps.filter(s => s.itemConsumed === logId && s.action.startsWith('fletch_') && fletchLevel >= s.minLevel);
    if (matching.length === 0) return null;
    return matching.reduce((best, s) => (s.minLevel > best.minLevel ? s : best));
}

/**
 * port: how far (in levels) a step's own minimum may lie below the best step the bot's level allows and still suit
 * it. Upstream picked any step the level allowed, at random: most steps run from their level to 99, so a level-40
 * fighter drew chickens, goblins, cows, rats and spiders 9 times out of 21, a level-65 woodcutter normal trees and
 * oaks 2 times out of 7.
 */
export const SUITED_LEVEL_WINDOW = 10;
/** port: how often a bot still picks any step its level allows (a change of scene, as players do) */
export const STEP_VARIETY_CHANCE = 0.15;
/**
 * port: ...within this many levels of the best step's minimum: a change of scene, not a return to the start (any step
 * sent a third of the combat-20+ bots' time back to Lumbridge's chickens, cows and normal trees)
 */
export const VARIETY_LEVEL_WINDOW = 20;

/** The steps of a skill the level allows (and, with hasItems, the bot can do). */
export function eligibleSteps(skill: string, level: number, hasItems?: (step: SkillStep) => boolean): SkillStep[] {
    const steps = SkillProgression[skill];
    if (!steps || steps.length === 0) return [];
    const matching = steps.filter(s => level >= s.minLevel && level <= s.maxLevel);
    return hasItems ? matching.filter(hasItems) : matching;
}

/**
 * port: the eligible steps that suit the level: those within SUITED_LEVEL_WINDOW of the best minimum among them (a
 * level-40 fighter: hobgoblins, giants and Al Kharid warriors; a level-35 woodcutter: oaks and willows).
 */
export function suitedSteps(eligible: SkillStep[], window = SUITED_LEVEL_WINDOW): SkillStep[] {
    if (eligible.length === 0) return eligible;
    let best = 0;
    for (const s of eligible) best = Math.max(best, s.minLevel);
    // port (the realism work, phase 3): a step with its own band of levels suits the whole band (eligible: it is in it)
    return eligible.filter(s => s.levelBand === true || s.minLevel >= best - window);
}

/** port: is this step below what the level suits (or outside its level range)? */
export function isStepOutgrown(skill: string, step: SkillStep, level: number, hasItems?: (step: SkillStep) => boolean): boolean {
    if (level < step.minLevel || level > step.maxLevel) return true;
    const eligible = eligibleSteps(skill, level, hasItems);
    if (!eligible.includes(step)) eligible.push(step);
    return !suitedSteps(eligible).includes(step);
}

/** port: how near a step must be to count half as much (tiles): nearer steps are picked more often */
const STEP_NEAR_TILES = 200;

/**
 * (the variety work, round 1, Track D) how a pick weighs its spots beyond crowd and distance: `weigh`, a caller's own
 * weight per step (the planner's: a bot's home spot and its name's theme, port/BotFavourites); `within`, only the steps
 * within that many tiles of `from` when there are any (firemaking: the lanes near the bank its logs come from).
 */
export interface PickOptions {
    weigh?: (step: SkillStep) => number;
    within?: number;
}

/**
 * (the variety work, round 1, Track D: spot capacity and occupancy) a weight for every pick's steps, set by
 * port/BotSpots (the bots already on a spot against what it holds: max(0.05, 1 - occupants / capacity)). A hook, as
 * this module imports nothing; none (1) until it is set, as in the tests that load this module alone.
 */
let spotWeight: ((step: SkillStep) => number) | null = null;
export function setSpotWeight(weight: ((step: SkillStep) => number) | null): void {
    spotWeight = weight;
}

function pickStep(eligible: SkillStep[], from?: [number, number], opts?: PickOptions): SkillStep | null {
    if (eligible.length === 0) return null;
    // port: mostly a step that suits the level, sometimes any within VARIETY_LEVEL_WINDOW (see SUITED_LEVEL_WINDOW)
    const pool = suitedSteps(eligible, Math.random() < STEP_VARIETY_CHANCE ? VARIETY_LEVEL_WINDOW : SUITED_LEVEL_WINDOW);
    return pickNear(pool, from, opts);
}

/** (the variety work, round 1, Track D) a step's spot on the surface (a dungeon's: its way in) */
export function stepSurface(step: SkillStep): [number, number] {
    return surfaceOf(step.location[0], step.location[1]);
}

/** (the variety work, round 1, Track D) a step's spot's distance (tiles, on the surface: a dungeon's by its way in) from a tile */
export function stepDistance(step: SkillStep, x: number, z: number): number {
    const f = surfaceOf(x, z);
    const [sx, sz] = surfaceOf(step.location[0], step.location[1]);
    return Math.max(Math.abs(sx - f[0]), Math.abs(sz - f[1]));
}

/** port: one of the steps (one die), the nearer `from` the likelier; without `from` any of them alike (by their crowd) */
function pickNear(pool: SkillStep[], from?: [number, number], opts?: PickOptions): SkillStep | null {
    // (the variety work, round 1, Track D: `within`: the near ones only, when there are some)
    if (from && opts?.within !== undefined && pool.length > 1) {
        const near = pool.filter(s => stepDistance(s, from[0], from[1]) <= opts.within!);
        if (near.length > 0) pool = near;
    }
    if (pool.length < 2) return pool[Math.floor(Math.random() * pool.length)] ?? null;
    // port: the nearer the bot, the likelier: weight 1 / (1 + (d / STEP_NEAR_TILES)²), 1 at the spot, 0.2 at 400 tiles;
    // port (the realism work, phase 3): times the spot's crowd (2004's crowd spots weigh more: SkillStep.crowd), and a
    // dungeon's spot (and a bot underground) measured from its way in on the surface: 6,400 tiles off as it is, the hill
    // giants, the ice dungeon and Taverley's druids were all but never picked from the surface
    const f = from ? surfaceOf(from[0], from[1]) : null;
    const near = (s: SkillStep): number => {
        if (!f) return 1;
        const [sx, sz] = surfaceOf(s.location[0], s.location[1]);
        return 1 / (1 + (Math.max(Math.abs(sx - f[0]), Math.abs(sz - f[1])) / STEP_NEAR_TILES) ** 2);
    };
    // (the variety work, round 1, Track D: times how full the spot is (spotWeight) and the caller's own weight)
    const weights = pool.map(s => (s.crowd ?? 1) * near(s) * (spotWeight ? spotWeight(s) : 1) * (opts?.weigh ? opts.weigh(s) : 1));
    let roll = Math.random() * weights.reduce((a, b) => a + b, 0);
    for (let i = 0; i < pool.length; i++) {
        roll -= weights[i];
        if (roll <= 0) return pool[i];
    }
    return pool[pool.length - 1];
}

/** port (the realism work, phase 3): where a tile is for a walk on the surface: a dungeon's (z > 6400) is its way in. */
function surfaceOf(x: number, z: number): [number, number] {
    // (the variety work, round 1, Track D) the runecrafting realm (the essence mine and the altars' temples, 274's strip
    // at z 4700-4900): the way in, Aubury's rune shop (an essence run's start; an altar's ruins are elsewhere, but no pick
    // weighs those: RunecraftingTask chooses its altar)
    if (z >= 4700 && z < 4900 && x < 2960) return [3253, 3401];
    if (z <= 6400) return [x, z];
    const [ex, ez] = dungeonRoute(x, z).entrance;
    return [ex, ez];
}

/** `from`: where the bot is (port: nearer steps are picked more often). */
export function getProgressionStep(skill: string, level: number, hasItems?: (toolItemIds: number[]) => boolean, from?: [number, number], opts?: PickOptions): SkillStep | null {
    return pickStep(eligibleSteps(skill, level, hasItems ? s => hasItems(s.toolItemIds) : undefined), from, opts);
}

/** port: getProgressionStep with a predicate on the whole step (a combat step's weapon, a fishing spot's danger). */
export function getProgressionStepWhere(skill: string, level: number, usable: (step: SkillStep) => boolean, from?: [number, number], opts?: PickOptions): SkillStep | null {
    return pickStep(eligibleSteps(skill, level, usable), from, opts);
}

/**
 * port: the step a task moves on to when its bot's level rose: a new one only when the current step is outgrown at
 * this level (or the level left its range), among those the bot can do; otherwise null (keep the current one).
 * Upstream's tasks drew a random step every tick and took it whenever its minimum was higher: within a few ticks of
 * starting, a task had jumped to the highest step the level allowed, whether the bot had its tools (a lobster pot,
 * a steel scimitar) or its materials (a cook with raw shrimp sent off to cook swordfish) or not.
 */
export function levelUpStep(skill: string, current: SkillStep, level: number, usable?: (step: SkillStep) => boolean, from?: [number, number]): SkillStep | null {
    if (!isStepOutgrown(skill, current, level, usable)) return null;
    const eligible = eligibleSteps(skill, level, usable);
    const suited = suitedSteps(eligible);
    // port: `from` (where the bot is): the nearer the likelier, as the planner's pick (drawn anywhere, a level-up at a
    // spot near the bot could send it across the map)
    return suited.length > 0 ? pickNear(suited, from) : null;
}

